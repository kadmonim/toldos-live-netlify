// The language someone picked with EN/עב. Until they do, visitors in the US get English and
// everyone else the family's first language (setFamily). An older version saved 'he' on every visit
// under tree.lang without anyone choosing it, so only an old 'en' there counts as a choice.
const LANG_KEY = 'tree.lang.v2';
const chosen = localStorage.getItem(LANG_KEY) ?? (localStorage.getItem('tree.lang') === 'en' ? 'en' : null);
let lang = chosen ?? 'he';

export const getLang = () => lang;
export const otherLang = () => (lang === 'he' ? 'en' : 'he');

export function setLang(l, remember = true) {
  lang = l;
  if (remember) localStorage.setItem(LANG_KEY, l);
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'he' ? 'rtl' : 'ltr';
}

/** t('key'), t('key', 'en'), or t('key', lang, ...args) for strings that take values. */
export function t(key, l = lang, ...args) {
  const v = S[key]?.[l === 'he' ? 0 : 1];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}

setLang(lang, false);

/** The site's family: its name everywhere the app names itself, and its first language. */
export function setFamily(f) {
  S.appName = [f.he, f.en];
  // The visitor's country is marked on the page by the edge function (edge-functions/coming-soon.js).
  if (!chosen) setLang(document.documentElement.dataset.country === 'US' ? 'en' : f.lang, false);
  const [one, two] = f.lang === 'en' ? ['en', 'he'] : ['he', 'en'];
  document.title = `${t('treeOf', one, f[one])} · ${t('treeOf', two, f[two])}`;
}
